"""Follow-up 2, B5: how each dipole model builds its APT (illustration, not evidence).

All three dipole models write the molecular dipole as mu = sum_i q_i r_i + sum_i p_i
(atomic charges q_i, atomic dipoles p_i):
- POLAR-1 (mace-torch PolarMACE): q = l=0, p = l=1 coefficients of the learned charge density
  (mace/modules/utils.py compute_total_charge_dipole_permuted, CS order [2, 0, 1]);
- MDP (mace-torch AtomicDielectricMACE) and MACE4IR (mace_dipole_core AtomicDielectricMACE):
  outputs "charges" and "atomic_dipoles", mu = sum p + sum q r.
Differentiating gives the three terms of the APT (eq:ccfdf):
  dmu_b/dr_ja = q_j delta_ab  +  sum_i r_ib dq_i/dr_ja  +  sum_i dp_ib/dr_ja
               (charge)          (charge flux)              (atomic-dipole flux)
Checks: the reconstructed mu equals the model's dipole; the three terms sum to the full APT.
The split is model-internal and not unique: two models can split the same APT differently.

Projected on the B3LYP modes at the B3LYP geometry (as in B1), each term gives a vector
dmu/dQ; its share of the band is (v_term . v_total) / |v_total|^2 (shares sum to 1).
Writes b5_tables.md.
"""

from __future__ import annotations

import logging
import sys
import warnings
from pathlib import Path

import numpy as np
import torch

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(HERE))
logging.disable(logging.CRITICAL)
warnings.filterwarnings("ignore")
from ase import Atoms  # noqa: E402
from b1_b2_analyse import KMMOL, fchk, merge_degenerate, normal_modes  # noqa: E402

from mace_gaussian.calculators import dipole_factory  # noqa: E402

BOHR = 0.529177210903
MOLS = ["methanol", "formic_acid_trans", "carbon_dioxide"]
MODELS = {"mace_polar1": "POLAR-1", "mace_mdp": "MDP", "mace_ml": "MACE4IR"}


def raw(model):
    d = dipole_factory.get_calculator(model)
    if model == "mace_polar1":
        d._ensure_calculator()
        return d.calc
    if model == "mace_mdp":
        d._ensure_calculator()
        return d.calc
    d.mace_calc._ensure_calculator()  # MACE4IR: mace_dipole_core calculator, loaded lazily
    return d.mace_calc.calc


def charges_dipoles(calc, model, atoms):
    batch = calc._atoms_to_batch(atoms)
    bd = calc._clone_batch(batch).to_dict()
    pos = bd["positions"]
    pos.requires_grad_(True)
    net = calc.models[0]
    if model == "mace_polar1":
        out = net(bd, training=True)
        coef = out["density_coefficients"]
        q = coef[:, 0]
        p = coef[:, 1:4][:, [2, 0, 1]]
    else:
        out = net(bd, training=True, compute_dielectric_derivatives=False)
        q = out["charges"]
        p = out["atomic_dipoles"]
    mu_model = out["dipole"].reshape(-1)[:3]
    return pos, q, p, mu_model


def decompose(calc, model, atoms):
    pos, q, p, mu_model = charges_dipoles(calc, model, atoms)
    n = len(atoms)
    mu_rec = (q[:, None] * pos).sum(0) + p.sum(0)
    dq = torch.zeros((n, n, 3), dtype=pos.dtype, device=pos.device)
    for i in range(n):
        dq[i] = torch.autograd.grad(q[i], pos, retain_graph=True)[0]
    dp = torch.zeros((n, 3, n, 3), dtype=pos.dtype, device=pos.device)
    for i in range(n):
        for b in range(3):
            dp[i, b] = torch.autograd.grad(p[i, b], pos, retain_graph=True)[0]
    r = pos.detach()
    qd = q.detach()
    t_charge = torch.zeros((n, 3, 3), dtype=pos.dtype, device=pos.device)
    for j in range(n):
        t_charge[j] = qd[j] * torch.eye(3, dtype=pos.dtype, device=pos.device)
    t_cflux = torch.einsum("ib,ija->jab", r, dq)  # [j, a, b]
    t_dflux = torch.einsum("ibja->jab", dp)
    to_np = lambda t: t.reshape(3 * n, 3).cpu().numpy()  # noqa: E731
    sum_dq = dq.sum(0).abs().max().item()
    return dict(q=qd.cpu().numpy(), charge=to_np(t_charge), cflux=to_np(t_cflux),
                dflux=to_np(t_dflux), mu_err=float((mu_rec - mu_model).abs().max()),
                sum_dq=sum_dq)  # fmt: skip


def main():
    out = ["# B5 tables (generated by b5_decomposition.py)\n"]
    w = out.append
    w("Share of each APT term in the band's dmu/dQ, (v_term . v_total)/|v_total|^2, on B3LYP "
      "modes at the B3LYP geometry; bands with B3LYP harmonic intensity > 10 km/mol. "
      "Columns: charge / charge flux / dipole flux; I = model intensity (km/mol).\n")  # fmt: skip
    apt_ref = {m: np.load(HERE / f"b1_apt_{m}.npz") for m in MODELS}
    res = {}
    for m in MODELS:
        calc = raw(m)
        for mol in MOLS:
            f = fchk(mol)
            atoms = Atoms(numbers=[int(z) for z in _z(mol)], positions=f["x"] * BOHR)
            atoms.info.update(charge=0.0, spin=1.0)
            d = decompose(calc, m, atoms)
            full = d["charge"] + d["cflux"] + d["dflux"]
            ref = apt_ref[m][f"{mol}/apt"]
            d["check_apt"] = float(np.abs(full - ref).max())
            res[(m, mol)] = d
    w("Checks (max abs): " + "; ".join(
        f"{MODELS[m]} {mol}: mu {res[(m, mol)]['mu_err']:.1e} e*A, APT {res[(m, mol)]['check_apt']:.1e} e, "
        f"sum dq/dr {res[(m, mol)]['sum_dq']:.1e}" for m in MODELS for mol in MOLS) + "\n")  # fmt: skip
    for mol in MOLS:
        f = fchk(mol)
        freqs, disp = normal_modes(f["x"], f["m"], f["hess"])
        ib = KMMOL * np.sum((f["apt"].T @ disp) ** 2, 0)
        w(f"\n## {mol}\n")
        w("Atomic charges q (e): " + "; ".join(
            f"{MODELS[m]} " + " ".join(f"{v:+.2f}" for v in res[(m, mol)]["q"]) for m in MODELS))  # fmt: skip
        w("\n| mode (B3LYP cm-1) | B3LYP I | " + " | ".join(
            f"{MODELS[m]}: I, charge / c-flux / d-flux" for m in MODELS) + " |")  # fmt: skip
        w("|---" * 5 + "|")
        for k in np.argsort(freqs):
            if ib[k] <= 10:
                continue
            cells = []
            for m in MODELS:
                d = res[(m, mol)]
                v = {t: d[t].T @ disp[:, k] for t in ("charge", "cflux", "dflux")}
                tot = v["charge"] + v["cflux"] + v["dflux"]
                sh = {t: float(v[t] @ tot / (tot @ tot)) for t in v}
                cells.append(f"{KMMOL * tot @ tot:.0f}, {sh['charge']:+.2f} / {sh['cflux']:+.2f} / {sh['dflux']:+.2f}")
            w(f"| {freqs[k]:.0f} | {ib[k]:.0f} | " + " | ".join(cells) + " |")
    (HERE / "b5_tables.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


def _z(mol):
    t = (ROOT / "campaigns/2026" / mol / f"{mol}_freq_anharm.fchk").read_text()
    i = t.index("Atomic numbers")
    n = int(t[i : t.index("\n", i)].split("N=")[1])
    return [int(v) for v in t[t.index("\n", i) + 1 :].split()[:n]]


if __name__ == "__main__":
    _ = merge_degenerate
    main()
