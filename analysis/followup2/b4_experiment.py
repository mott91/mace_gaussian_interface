"""Follow-up 2, B4: region-integrated gas-phase IR intensities against experiment (5 non-acids).

Experiment: NIST Quantitative Infrared Database (b4_experiment/nist_quant_ir/*.jdx), gas at
23 C and 101.3 kPa, Happ-Genzel, 1.929 cm-1 resolution, 574.7-3974.6 cm-1; y = base-10
absorption coefficient a in (umol/mol)^-1 m^-1, i.e. A10 = a * c[ppm] * l[m].
  sigma(nu) [m^2/molecule] = ln(10) * a / n_ppm,   n_ppm = 1e-6 * P / (k T)
  I [km/mol] = integral sigma d(nu~[cm^-1]) * 100 * N_A / 1000
Integrated over regions; the calculated value of a region is the sum over the bands that fall
in it:
- harmonic: fundamentals, by harmonic frequency (B3LYP log; dipole models on the B3LYP modes
  from B1, i.e. the dipole model alone);
- VPT2: fundamentals + overtones + combination bands, by anharmonic frequency (bands.csv of the
  campaign; B3LYP and the dipole models on the MACE-OMOL surface). Experiment contains all of
  these (and hot bands), so VPT2 is the fairer comparison.
Writes b4_tables.md.
"""

from __future__ import annotations

import csv
import logging
import re
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(HERE))
logging.disable(logging.CRITICAL)
from b1_b2_analyse import KMMOL, fchk, normal_modes  # noqa: E402

from mace_gaussian.gaussian.parser import parse_gaussian_log  # noqa: E402

EXP = HERE / "b4_experiment/nist_quant_ir"
CAMP = ROOT / "campaigns/2026"
BANDS = CAMP / "figures/supervisor/data/bands.csv"
MOLS = ["methanol", "ethanol", "isopropanol", "1-butanol", "sulfur_dioxide"]
REGIONS = {
    "default": [("575-1550 (fingerprint)", 575, 1550), ("2600-3300 (C-H)", 2600, 3300),
                ("3300-3975 (O-H)", 3300, 3975), ("575-3975 (all)", 575, 3975)],
    "sulfur_dioxide": [("1050-1250 (nu1)", 1050, 1250), ("1250-1450 (nu3)", 1250, 1450),
                       ("575-3975 (all)", 575, 3975)],
}  # fmt: skip
DIP = {"mace_polar1": "POLAR-1", "mace_mdp": "MDP", "mace_ml": "MACE4IR"}
KB, NA = 1.380649e-23, 6.02214076e23


def read_jdx(p: Path):
    t = p.read_text().split("\n")
    hdr = {}
    for line in t:
        if line.startswith("##") and "=" in line:
            k, v = line[2:].split("=", 1)
            hdr[k.strip()] = v.strip()
    i0 = next(i for i, line in enumerate(t) if line.startswith("##XYDATA"))
    ys = []
    for line in t[i0 + 1 :]:
        if line.startswith("##"):
            break
        # AFFN: a sign also separates values ("56144-51474" = 56144, -51474); first token is X
        ys += [float(v) for v in re.findall(r"[+-]?\d+\.?\d*(?:[eE][+-]?\d+)?", line)[1:]]
    x0, dx = float(hdr["FIRSTX"]), float(hdr["DELTAX"])
    x = x0 + dx * np.arange(len(ys))
    y = np.array(ys) * float(hdr["YFACTOR"])
    T = float(hdr["TEMPERATURE"].split()[0]) + 273.15
    P = float(hdr["PRESSURE"].split()[0]) * 1e3
    sigma = np.log(10) * y / (1e-6 * P / (KB * T))  # m^2 per molecule
    return x, sigma


def exp_region(x, s, lo, hi):
    m = (x >= lo) & (x <= hi)
    return float(np.trapz(s[m], x[m]) * 100 * NA / 1000)


def main():
    rows = list(csv.DictReader(BANDS.open()))
    out = ["# B4 tables (generated by b4_experiment.py)\n"]
    w = out.append
    b1 = {d: np.load(HERE / f"b1_apt_{d}.npz") for d in DIP}
    cells_all = []
    for mol in MOLS:
        x, s = read_jdx(EXP / f"{mol}.jdx")
        f = fchk(mol)
        freqs, disp = normal_modes(f["x"], f["m"], f["hess"])
        g = parse_gaussian_log(str(CAMP / mol / f"{mol}_freq_anharm.log"))["harmonic"]
        harm_b3 = [(r["freq_cm"], r["ir_intensity"]) for r in g]
        harm_dip = {d: list(zip(freqs, KMMOL * np.sum((b1[d][f"{mol}/apt"].T @ disp) ** 2, 0))) for d in DIP}
        # POLAR-1 field-response APT (B2; sign: the model adds +E.mu, so APT = -stored)
        apt_f = -b1["mace_polar1"][f"{mol}/apt_field_0.001"]
        harm_field = list(zip(freqs, KMMOL * np.sum((apt_f.T @ disp) ** 2, 0)))
        vpt2 = {}
        mol_rows = [r for r in rows if r["molecule"] == mol and r["energy_model"] == "mace_omol"]
        seen = set()
        vpt2["B3LYP"] = []
        for r in mol_rows:
            key = (r["band_type"], r["i"], r["j"], r["l"])
            if key in seen or not r["dft_anharmonic"]:
                continue
            seen.add(key)
            vpt2["B3LYP"].append((float(r["dft_anharmonic"]), float(r["dft_intensity"] or 0)))
        for d in DIP:
            vpt2[d] = [(float(r["ml_anharmonic"]), float(r["ml_intensity"] or 0)) for r in mol_rows
                       if r["dipole_model"] == d and r["ml_anharmonic"] and r["ml_intensity"]]  # fmt: skip
        w(f"\n## {mol} (km/mol)\n")
        w("| region | experiment | B3LYP harm | B3LYP VPT2 | " + " | ".join(f"{v} harm (B3LYP modes)" for v in DIP.values())
          + " | POLAR-1 (field) harm | " + " | ".join(f"{v} VPT2 (OMOL)" for v in DIP.values()) + " |")  # fmt: skip
        w("|---" * (5 + 2 * len(DIP)) + "|")
        for lab, lo, hi in REGIONS.get(mol, REGIONS["default"]):
            e = exp_region(x, s, lo, hi)
            summ = lambda bl: sum(i for fr, i in bl if lo <= fr <= hi)  # noqa: E731
            vals = {"B3LYP harm": summ(harm_b3), "B3LYP VPT2": summ(vpt2["B3LYP"]),
                    **{f"{DIP[d]} harm": summ(harm_dip[d]) for d in DIP},
                    "POLAR-1 (field) harm": summ(harm_field),
                    **{f"{DIP[d]} VPT2": summ(vpt2[d]) for d in DIP}}  # fmt: skip
            w(f"| {lab} | {e:.1f} | " + " | ".join(f"{v:.1f}" for v in vals.values()) + " |")
            if "(all)" not in lab:
                cells_all.append((mol, lab, e, vals))
    # summary over the region cells
    w("\n## Summary over the molecule × region cells (without the 'all' totals)\n")
    w("| method | cells | median calc/exp | mean abs(log10(calc/exp)) | within ±25 % |")
    w("|---|---|---|---|---|")
    keys = list(cells_all[0][3])
    for k in keys:
        r = np.array([c[3][k] / c[2] for c in cells_all if c[2] > 1])
        w(f"| {k} | {len(r)} | {np.median(r):.2f} | {np.mean(np.abs(np.log10(r))):.3f} | {100 * np.mean(np.abs(r - 1) < 0.25):.0f} % |")
    (HERE / "b4_tables.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
