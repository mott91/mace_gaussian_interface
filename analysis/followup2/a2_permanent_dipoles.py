"""Follow-up 2, A2: permanent dipole mu0 of the three dipole models against B3LYP.

Read only from existing campaign logs, no new model evaluations:
- ML: Gaussian archive "Dipole=" of each run's gaussian_freq.log (atomic units, input orientation),
  i.e. the dipole the model handed to Gaussian at the run's reference geometry (the minimum of
  that energy model); geometry = the first "Input orientation" block of the same log.
  (The per-call "Dipole moment=" lines are in the standard orientation and are not used.)
- B3LYP: archive "Dipole=" of <mol>/<mol>_freq_anharm.log at its minimum; geometry = the last
  "Input orientation" block (nosymm, so input = computational frame).
The ML dipole is rotated into the B3LYP frame with the Kabsch rotation of the ML geometry onto
the B3LYP geometry (same atom order). Angles only where |mu_B3LYP| > 0.1 D.

Writes a2_dipoles.csv and a2_tables.md next to this script.
"""

from __future__ import annotations

import csv
import re
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT))
from mace_gaussian.analysis.mode_matching import kabsch_rotation  # noqa: E402

C = ROOT / "campaigns/2026"
AU2D = 2.54174623
ENERGY = ["mace_anicc", "mace_omol", "mace_off", "mace_polar"]
DIPOLE = ["mace_polar1", "mace_mdp", "mace_ml"]
ELAB = {"mace_anicc": "ANI-cc", "mace_omol": "OMOL", "mace_off": "OFF", "mace_polar": "POLAR"}
DLAB = {"mace_polar1": "POLAR-1", "mace_mdp": "MDP", "mace_ml": "MACE4IR"}
SYMTOP = {"ammonia", "phosphine"}


def archive_dipole(text: str) -> np.ndarray:
    i = text.rfind("1\\1\\")
    arch = text[i:].replace("\n ", "")
    m = re.search(r"Dipole=([-\d\.]+),([-\d\.]+),([-\d\.]+)", arch)
    return np.array([float(g) for g in m.groups()]) * AU2D


def orientation(text: str, which: str) -> np.ndarray:
    blocks = text.split("Input orientation:")[1:]
    blk = blocks[0] if which == "first" else blocks[-1]
    rows = []
    for line in blk.split("\n")[5:]:
        p = line.split()
        if len(p) != 6:
            break
        rows.append([float(v) for v in p[3:6]])
    return np.array(rows)


def main():
    rows = []
    for mol_dir in sorted((C / "comparison_results").iterdir()):
        mol = mol_dir.name
        blog = C / mol / f"{mol}_freq_anharm.log"
        if not blog.exists():
            continue
        bt = blog.read_text()
        mu_b, xb = archive_dipole(bt), orientation(bt, "last")
        for E in ENERGY:
            for D in DIPOLE:
                log = mol_dir / f"{E}_{D}" / "gaussian_freq.log"
                if not log.exists():
                    continue
                t = log.read_text()
                mu, x = archive_dipole(t), orientation(t, "first")
                R = kabsch_rotation(x, xb)  # row-vector convention: x_c @ R ~ xb_c
                mu_r = mu @ R
                rmsd = float(np.sqrt(np.mean(np.sum(((x - x.mean(0)) @ R - (xb - xb.mean(0))) ** 2, 1))))
                nb = np.linalg.norm(mu_b)
                ang = (float(np.degrees(np.arccos(np.clip(mu_r @ mu_b / (np.linalg.norm(mu_r) * nb), -1, 1))))
                       if nb > 0.1 else np.nan)  # fmt: skip
                rows.append(dict(mol=mol, E=E, D=D, mu_b3lyp=nb, mu_ml=float(np.linalg.norm(mu)),
                                 err=float(np.linalg.norm(mu) - nb), angle=ang,
                                 vec_err=float(np.linalg.norm(mu_r - mu_b)), kabsch_rmsd=rmsd))  # fmt: skip
    with (HERE / "a2_dipoles.csv").open("w", newline="") as fh:
        wr = csv.DictWriter(fh, fieldnames=list(rows[0]))
        wr.writeheader()
        wr.writerows(rows)

    out = ["# A2 tables (generated by a2_permanent_dipoles.py)\n"]
    w = out.append
    w(f"Kabsch RMSD ML -> B3LYP geometry: max {max(r['kabsch_rmsd'] for r in rows):.3f} A "
      "(frames consistent).\n")  # fmt: skip
    for lab, excl in (("without NH3/PH3", SYMTOP), ("all molecules", set())):
        w(f"\n## {lab}\n")
        w("| energy model | metric | " + " | ".join(DLAB[D] for D in DIPOLE) + " | molecules |")
        w("|---" * 6 + "|")
        for E in ENERGY:
            for met, f, lab2 in (("err", lambda v: np.mean(np.abs(v)), "MAE of |mu| (D)"),
                                 ("err", np.mean, "mean signed |mu| error (D)"),
                                 ("vec_err", np.mean, "mean |mu_ML - mu_B3LYP| (D)"),
                                 ("angle", np.nanmedian, "median angle (deg)")):  # fmt: skip
                vals = {}
                for D in DIPOLE:
                    v = np.array([r[met] for r in rows if r["E"] == E and r["D"] == D
                                  and r["mol"] not in excl])  # fmt: skip
                    vals[D] = f(v)
                n = len({r["mol"] for r in rows if r["E"] == E and r["mol"] not in excl})
                best = min(DIPOLE, key=lambda D: abs(vals[D]))
                cells = [(f"**{vals[D]:.3f}**" if D == best else f"{vals[D]:.3f}") for D in DIPOLE]
                w(f"| {ELAB[E]} | {lab2} | " + " | ".join(cells) + f" | {n} |")
    # per molecule, OMOL geometry
    w("\n## Per molecule, OMOL runs: |mu| in D (angle to B3LYP in deg)\n")
    w("| molecule | B3LYP | " + " | ".join(DLAB[D] for D in DIPOLE) + " |")
    w("|---" * 5 + "|")
    for mol in sorted({r["mol"] for r in rows}):
        rr = {r["D"]: r for r in rows if r["mol"] == mol and r["E"] == "mace_omol"}
        if len(rr) < 3:
            continue
        cells = []
        for D in DIPOLE:
            a = rr[D]["angle"]
            cells.append(f"{rr[D]['mu_ml']:.2f}" + ("" if np.isnan(a) else f" ({a:.0f})"))
        w(f"| {mol} | {rr[DIPOLE[0]]['mu_b3lyp']:.2f} | " + " | ".join(cells) + " |")
    (HERE / "a2_tables.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
